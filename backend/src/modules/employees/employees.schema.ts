import { z } from 'zod';
import { Role } from '@prisma/client';

export const createEmployeeSchema = z.object({
  email: z.string().email('Invalid email address'),
  password: z.string().min(6, 'Password must be at least 6 characters long'),
  full_name: z.string().min(2, 'Full name must be at least 2 characters long'),
  role: z.nativeEnum(Role).default(Role.EMPLOYEE),
  department: z.string().default('General'),
  position: z.string().default('Staff'),
  phone: z.string().nullable().optional(),
  join_date: z.string().or(z.date()).nullable().optional(),
  annual_leave_quota: z.number().int().min(0).default(12),
  annual_leave_used: z.number().int().min(0).default(0),
  office_id: z.string().nullable().optional(),
  shift_id: z.string().nullable().optional(),
  company_id: z.string().nullable().optional(),
  company_name: z.string().nullable().optional(),
  is_wfh_allowed: z.boolean().default(false),
  // Team PGE Comprehensive Fields
  employee_id_number: z.string().nullable().optional(),
  nickname: z.string().nullable().optional(),
  birth_place: z.string().nullable().optional(),
  birth_date: z.string().or(z.date()).nullable().optional(),
  gender: z.string().nullable().optional(),
  marital_status: z.string().nullable().optional(),
  children_count: z.number().int().nullable().optional(),
  blood_type: z.string().nullable().optional(),
  religion: z.string().nullable().optional(),
  ktp_number: z.string().nullable().optional(),
  kk_number: z.string().nullable().optional(),
  emergency_contact_phone: z.string().nullable().optional(),
  address: z.string().nullable().optional(),
  bank_uob: z.string().nullable().optional(),
  bank_other: z.string().nullable().optional(),
  contract_signed_date: z.string().or(z.date()).nullable().optional(),
  employment_status: z.string().nullable().optional(),
  work_history: z.string().nullable().optional(),
  disc_work: z.string().nullable().optional(),
  disc_home: z.string().nullable().optional(),
  vak: z.string().nullable().optional(),
  iq_score: z.string().nullable().optional(),
  iq_eling_healing: z.string().nullable().optional(),
  stifin: z.string().nullable().optional(),
});

